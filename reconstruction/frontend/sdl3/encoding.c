uint32_t tera_cp437_codepoint(unsigned char byte)
{
    return byte<128 ? byte : high[byte-128];
}
int tera_cp437_utf8(const char *source,char *out,size_t capacity)
{
    const unsigned char *p;size_t needed=1,offset=0;
    if(!source || !out) return 0;
    for(p=(const unsigned char *)source;*p;++p) {
        uint32_t cp=tera_cp437_codepoint(*p);
        needed+=cp<128 ? 1 : cp<2048 ? 2 : 3;
    }
    if(needed>capacity) return 0;
    for(p=(const unsigned char *)source;*p;++p) {
        uint32_t cp=tera_cp437_codepoint(*p);
        if(cp<128) out[offset++]=(char)cp;
        else if(cp<2048) {
            out[offset++]=(char)(0xc0u|(cp>>6));out[offset++]=(char)(0x80u|(cp&63u));
        } else {
            out[offset++]=(char)(0xe0u|(cp>>12));out[offset++]=(char)(0x80u|((cp>>6)&63u));out[offset++]=(char)(0x80u|(cp&63u));
        }
    }
    out[offset]=0;return 1;
}